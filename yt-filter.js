    function matchLexicon(text, kind) {
        const phrases = lexicons[kind]?.phrases;

        if (!phrases?.length) {
            return [];
        }

        const value = lower(text);

        return phrases.filter(entry => {
            if (!entry.t) {
                return false;
            }

            const term = entry.t.toLocaleLowerCase();

            // Frases: substring. Unigramas curtos exigem fronteira
            // de palavra (evita "te"⊂"tech", "ele"⊂"elevenlabs").
            if (term.includes(" ")) {
                return value.includes(term);
            }

            try {
                const esc = term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
                return new RegExp(
                    `(^|[^\\p{L}\\p{N}_])${esc}(?![\\p{L}\\p{N}_])`,
                    "u"
                ).test(value);
            } catch {
                return value.includes(term);
            }
        });
    }

    function updateLexiconStatus() {
        for (const kind of LEXICON_KINDS) {
            document.querySelector(`#yt-ai-lexicon-status-${kind}`)?.replaceChildren(
                document.createTextNode(
                    `${kind}: ${lexicons[kind].status}`
                )
            );
        }
    }

    function loadCache() {
        try {
            const raw = localStorage.getItem(STORAGE_KEY);
            const parsed = raw ? JSON.parse(raw) : {};
            return new Map(Object.entries(parsed));
        } catch {
            return new Map();
        }
    }

