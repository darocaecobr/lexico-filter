    let scanQueued = false;

    function scheduleScan() {
        if (scanQueued) {
            return;
        }

        scanQueued = true;

        requestAnimationFrame(() => {
            scanQueued = false;
            scan();
        });
    }

    const observer =
        new MutationObserver(
            mutations => {
                for (const mutation of mutations) {
                    if (
                        mutation.addedNodes.length > 0
                    ) {
                        scheduleScan();
                        return;
                    }
                }
            }
        );

    function sliderRow(panel, { key, label, min, max, step, percent }) {
        const row = document.createElement("label");
        row.className = "yt-ai-row";

        const format = value => percent
            ? `${Math.round(Number(value) * 100)}%`
            : Number(value).toFixed(2);

        const head = document.createElement("div");
        head.className = "yt-ai-row-head";

        const name = document.createElement("span");
        name.textContent = label;

        const value = document.createElement("span");
        value.className = "yt-ai-val";
        value.textContent = format(CONFIG[key]);

        head.appendChild(name);
        head.appendChild(value);

        const input = document.createElement("input");
        input.type = "range";
        input.min = String(min);
        input.max = String(max);
        input.step = String(step);
        input.value = String(CONFIG[key]);
        input.dataset.key = key;

        input.addEventListener("input", () => {
            CONFIG[key] = Math.max(min, Math.min(max, Number(input.value)));
            value.textContent = format(CONFIG[key]);
            saveSettings();
            clearScoreCache();
            scan();
        });

        row.appendChild(head);
        row.appendChild(input);
        panel.appendChild(row);

        return row;
    }

    function intRow(panel, { key, label, min, max, step }) {
        const row = document.createElement("label");
        row.className = "yt-ai-row";

        const head = document.createElement("div");
        head.className = "yt-ai-row-head";

        const name = document.createElement("span");
        name.textContent = label;

        const input = document.createElement("input");
        input.type = "number";
        input.className = "yt-ai-num";
        input.min = String(min);
        input.max = String(max);
        input.step = String(step);
        input.value = String(CONFIG[key]);
        input.dataset.key = key;

        input.addEventListener("change", () => {
            let value = Number(input.value);

            if (!Number.isFinite(value)) {
                input.value = String(CONFIG[key]);
                return;
            }

            value = Math.max(min, Math.min(max, value));
            CONFIG[key] = value;
            input.value = String(value);
            saveSettings();
            clearScoreCache();
            scan();
        });

        head.appendChild(name);
        head.appendChild(input);
        row.appendChild(head);
        panel.appendChild(row);

        return row;
    }

